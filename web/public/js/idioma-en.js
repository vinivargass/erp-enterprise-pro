// Motivos de status gerados pelo servidor; podem vir vários na mesma frase.
function motivos(s) {
  return s
    .replace(/Desconto de ([\d.]+)% acima da alçada do vendedor \(([\d.]+)%\)\./g, 'Discount of $1% above the sales rep authority ($2%).')
    .replace(/Limite de crédito excedido: limite ([\d.]+), comprometido ([\d.]+), pedido ([\d.]+)\./g, 'Credit limit exceeded: limit $1, committed $2, order $3.')
    .replace(/Aprovado automaticamente: dentro das alçadas e do limite de crédito\./g, 'Automatically approved: within discount authority and credit limit.')
    .replace(/^Aprovado por (\S+)\./, 'Approved by $1.')
    .replace(/Faturamento demonstrativo \(sem emissão fiscal\)\./g, 'Demo invoicing (no fiscal document).');
}

