// Tradução recursiva para trechos que trazem outra frase do sistema dentro (ex.: motivo de status).
function tr(s) {
  const k = String(s ?? '').trim();
  if (k in textos) return textos[k];
  for (const [re, troca] of padroes) if (re.test(k)) return k.replace(re, troca);
  return k;
}

